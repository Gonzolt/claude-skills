#!/usr/bin/env node
// Scaffold a Remotion project wired to products.json + the prepped frames.
// Usage: node scaffold.mjs ./work [--name brandokids] [--seconds 12]
import fs from 'fs';
import path from 'path';

const args = process.argv.slice(2);
const work = args[0] ?? './work';
const flag = (n, d) => { const i = args.indexOf(n); return i === -1 ? d : args[i + 1]; };
const NAME = flag('--name', 'brandokids');
const SECONDS = Number(flag('--seconds', 12));
const FPS = 30;

const products = JSON.parse(fs.readFileSync(path.join(work, 'products.json'), 'utf8'));
const shotsDir = path.join(work, 'shots');
if (!fs.existsSync(shotsDir)) {
  console.error(`No ${shotsDir} — run prep.sh first.`);
  process.exit(1);
}
const shots = fs.readdirSync(shotsDir).filter((f) => /\.(jpe?g|png)$/i.test(f));

// match prepped frames to products by slug prefix, then by role
const pick = (slug, role) => {
  const cands = shots.filter((f) => f.toLowerCase().startsWith(slug.toLowerCase()) &&
                                     f.toLowerCase().includes(role));
  return cands.sort()[0] ?? null;
};
// fall back to a looser match: any shot whose name shares the product's first word
const loose = (p, role) => {
  const key = p.slug.split('-')[0].toLowerCase();
  return shots.filter((f) => f.toLowerCase().startsWith(key) && f.toLowerCase().includes(role)).sort()[0] ?? null;
};

const scenes = products.map((p) => ({
  slug: p.slug,
  title: p.shortTitle,
  price: p.priceFormatted,
  hero: pick(p.slug, 'hero') ?? loose(p, 'hero'),
  detail: pick(p.slug, 'detail') ?? loose(p, 'detail'),
  motion: pick(p.slug, 'motion') ?? loose(p, 'motion'),
}));

const missing = scenes.filter((s) => !s.hero);
const root = path.join(work, 'video');
const pub = path.join(root, 'public', 'shots');
fs.mkdirSync(path.join(root, 'src'), { recursive: true });
fs.mkdirSync(pub, { recursive: true });
for (const f of shots) fs.copyFileSync(path.join(shotsDir, f), path.join(pub, f));

const DURATION = Math.round(SECONDS * FPS);

const w = (rel, content) => fs.writeFileSync(path.join(root, rel), content);

w('package.json', JSON.stringify({
  name: NAME, version: '1.0.0', private: true, type: 'module',
  scripts: {
    dev: 'remotion studio',
    render: `remotion render Ad out/${NAME}.mp4`,
  },
  dependencies: {
    '@remotion/cli': '^4.0.293', remotion: '^4.0.293',
    react: '^19', 'react-dom': '^19',
  },
  devDependencies: { '@types/react': '^19', typescript: '^5.5.0' },
}, null, 2));

w('tsconfig.json', JSON.stringify({
  compilerOptions: {
    target: 'ES2020', module: 'ESNext', moduleResolution: 'bundler',
    jsx: 'react-jsx', strict: true, esModuleInterop: true, skipLibCheck: true,
    lib: ['ES2020', 'DOM'],
  },
  include: ['src'],
}, null, 2));

w('remotion.config.ts', `import { Config } from '@remotion/cli/config';

Config.setVideoImageFormat('jpeg');
Config.setOverwriteOutput(true);
`);

w('src/data.ts', `// Generated by scaffold.mjs — real product data from the storefront.
// Prices come from Shopify; never hand-edit them.
export type Scene = {
  slug: string;
  title: string;
  price: string | null;
  hero: string | null;
  detail: string | null;
  motion: string | null;
};

export const scenes: Scene[] = ${JSON.stringify(scenes, null, 2)};
export const FPS = ${FPS};
export const DURATION = ${DURATION};
`);

w('src/index.ts', `import { registerRoot } from 'remotion';
import { RemotionRoot } from './Root';

registerRoot(RemotionRoot);
`);

w('src/Root.tsx', `import { Composition } from 'remotion';
import { Ad } from './Ad';
import { DURATION, FPS } from './data';

export const RemotionRoot: React.FC = () => (
  <Composition
    id="Ad"
    component={Ad}
    durationInFrames={DURATION}
    fps={FPS}
    width={1080}
    height={1920}
  />
);
`);

w('src/Frame.tsx', `import { AbsoluteFill, Img, staticFile, useCurrentFrame } from 'remotion';

// Handheld drift. A still frame held still reads as a photograph; the same
// frame with a slow irregular offset reads as video. Two out-of-phase sines
// beat a linear pan, which reads as a slideshow.
const drift = (f: number, seed: number) => {
  const a = Math.sin((f + seed * 37) / 47) + 0.45 * Math.sin((f + seed * 11) / 19);
  const b = Math.cos((f + seed * 23) / 53) + 0.45 * Math.cos((f + seed * 7) / 17);
  return { x: a * 9, y: b * 7, s: 1.045 + a * 0.004 };
};

export const Frame: React.FC<{ src: string; seed?: number }> = ({ src, seed = 0 }) => {
  const f = useCurrentFrame();
  const d = drift(f, seed);
  return (
    <AbsoluteFill style={{ backgroundColor: '#000', overflow: 'hidden' }}>
      <Img
        src={staticFile('shots/' + src)}
        style={{
          width: '100%', height: '100%', objectFit: 'cover',
          transform: \`translate(\${d.x}px, \${d.y}px) scale(\${d.s})\`,
        }}
      />
    </AbsoluteFill>
  );
};
`);

w('src/Caption.tsx', `import { AbsoluteFill, useCurrentFrame } from 'remotion';

// Sticker caption: pops on in 3 frames with a small overshoot. No fades —
// a fade reads as broadcast, and this is a social cut.
export const Caption: React.FC<{ text: string; price?: string | null; at?: number }> = ({
  text, price, at = 0,
}) => {
  const f = useCurrentFrame() - at;
  if (f < 0) return null;
  const t = Math.min(1, f / 3);
  const scale = t < 1 ? 0.8 + 0.28 * t : 1.04 - 0.04 * Math.min(1, (f - 3) / 3);

  return (
    <AbsoluteFill style={{ justifyContent: 'center', alignItems: 'center', padding: 60 }}>
      <div style={{ transform: \`scale(\${scale})\`, textAlign: 'center' }}>
        <div style={{
          display: 'inline-block', backgroundColor: '#F5F0EB', color: '#2B2320',
          padding: '18px 34px', borderRadius: 18, fontSize: 66, fontWeight: 800,
          fontFamily: 'Inter, Helvetica, Arial, sans-serif', letterSpacing: -1.5,
          boxShadow: '0 10px 30px rgba(0,0,0,0.28)',
        }}>{text}</div>
        {price ? (
          <div style={{ marginTop: 16 }}>
            <span style={{
              display: 'inline-block', backgroundColor: '#A2632F', color: '#fff',
              padding: '10px 24px', borderRadius: 999, fontSize: 44, fontWeight: 700,
              fontFamily: 'Inter, Helvetica, Arial, sans-serif',
            }}>{price}</span>
          </div>
        ) : null}
      </div>
    </AbsoluteFill>
  );
};
`);

w('src/Ad.tsx', `import { AbsoluteFill, Sequence } from 'remotion';
import { Frame } from './Frame';
import { Caption } from './Caption';
import { scenes, DURATION, FPS } from './data';

// Hard cuts only — no TransitionSeries, so no padding arithmetic.
// See references/edit.md for why, and for the structure below.
const HOOK = Math.round(1.0 * FPS);
const END = Math.round(1.5 * FPS);
const body = DURATION - HOOK - END;
const per = Math.floor(body / Math.max(1, scenes.length));
const heroLen = Math.round(per * 0.6);

export const Ad: React.FC = () => {
  const hook = scenes[0];
  return (
    <AbsoluteFill style={{ backgroundColor: '#F5F0EB' }}>
      {/* HOOK — lead with motion, never the hero. Legible by frame 15. */}
      <Sequence durationInFrames={HOOK}>
        <Frame src={hook?.motion ?? hook?.hero ?? ''} seed={0} />
        <Caption text="Ny høst hos Brando Kids" at={2} />
      </Sequence>

      {scenes.map((s, i) => {
        const from = HOOK + i * per;
        return (
          <Sequence key={s.slug} from={from} durationInFrames={per}>
            {/* hero, then an internal cut to detail — a single still held
                two seconds dies */}
            <Sequence durationInFrames={heroLen}>
              <Frame src={s.hero ?? s.detail ?? s.motion ?? ''} seed={i + 1} />
              <Caption text={s.title} price={s.price} at={3} />
            </Sequence>
            <Sequence from={heroLen} durationInFrames={per - heroLen}>
              <Frame src={s.detail ?? s.hero ?? ''} seed={i + 9} />
            </Sequence>
          </Sequence>
        );
      })}

      {/* END CARD */}
      <Sequence from={DURATION - END} durationInFrames={END}>
        <AbsoluteFill style={{
          backgroundColor: '#F5F0EB', justifyContent: 'center', alignItems: 'center',
          fontFamily: 'Inter, Helvetica, Arial, sans-serif', color: '#2B2320',
        }}>
          <div style={{ fontSize: 92, fontWeight: 800, letterSpacing: -3 }}>Brando Kids</div>
          <div style={{ fontSize: 46, marginTop: 14, color: '#A2632F', fontWeight: 600 }}>
            Find your style
          </div>
        </AbsoluteFill>
      </Sequence>
    </AbsoluteFill>
  );
};
`);

console.log(`Remotion project -> ${root}`);
console.log(`  ${scenes.length} scene(s), ${DURATION} frames @ ${FPS}fps (${SECONDS}s)`);
console.log(`  ${shots.length} frame(s) copied to public/shots/`);
for (const s of scenes) {
  console.log(`   ${s.title.padEnd(28)} hero:${s.hero ? '✓' : '—'} detail:${s.detail ? '✓' : '—'} motion:${s.motion ? '✓' : '—'}`);
}
if (missing.length) {
  console.log(`\n! ${missing.length} product(s) have no hero frame:`);
  missing.forEach((s) => console.log(`   ${s.title}`));
  console.log('  Name files raw/<slug>-hero-1.jpg so they match, or reshoot.');
  console.log('  Do not substitute a catalogue flat lay and call the scene done.');
}
const noPrice = scenes.filter((s) => !s.price);
if (noPrice.length) console.log(`\n! ${noPrice.length} scene(s) have no price — get the real one, never invent it.`);

console.log(`\nNext:\n  cd ${path.join(work, 'video')} && npm install && npm run render`);
